/* ============================================================================
 * 【文件导读】bgp_trace.c —— bgpd 追踪点(tracepoint)的“唯一定义编译单元”
 * ============================================================================
 * 本文件极短，作用是把 bgp_trace.h 里声明的那一大批 LTTng 追踪点**真正实例化
 * 编译一次**。LTTng 的约定是：声明放在头文件里，而探针的实际定义(probe 符号)
 * 必须在**恰好一个** .c 文件里生成一次，否则会重复定义 / 链接冲突。
 * 它通过两个宏完成：
 *   - TRACEPOINT_CREATE_PROBES : 让被包含的头展开出探针桩的**代码**。
 *   - TRACEPOINT_DEFINE        : 声明“本翻译单元负责定义这些追踪点”。
 *   （对比：bgp_trace.h 被其它源文件直接包含时这两个宏未定义，只生成声明。）
 * 因此本文件没有函数、没有运行时逻辑，只负责把定义“落地”一次。
 * ============================================================================
 */

/* 【生成探针桩代码】定义此宏后，头里每个 TRACEPOINT_EVENT 会展开成真正的探针
 * 定义代码，而不仅仅是声明。 */
#define TRACEPOINT_CREATE_PROBES
/* 【声明本翻译单元负责定义这些追踪点】LTTng 要求“定义”只出现在一个编译单元，
 * 以避免符号重复。 */
#define TRACEPOINT_DEFINE

/* zebra 基础头(FRR 通用基础设施)；追踪点字段里用到的一些类型也依赖它。 */
#include <zebra.h>

/* 【关键】包含声明头，配合上面两个宏在本翻译单元生成全部探针定义。 */
#include "bgp_trace.h"
